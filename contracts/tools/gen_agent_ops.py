    for name, dom, risk, on, phase, runs_as, timeout, params, result in OPS:
        write(f"ops/{name}.schema.json", {"$schema": D2020, "$id": f"{BASE}/ops/{name}.schema.json", "title": name,
                                          "$defs": {"params": params, "result": result}})
